// An instance made by an older release keeps working after an upgrade that only restarts it:
// `plinth start` (and so the Docker image, which re-runs `plinth init` only when its settings
// change) carries the release's compatibility flags into the instance's wrangler.jsonc.
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { after, describe, it } from "node:test";
import {
  parseJsonc,
  setupInstance,
  startInstance,
} from "../../../apps/worker/scripts/instance.mjs";

const home = mkdtempSync(path.join(tmpdir(), "plinth-upgrade-"));
after(() => rmSync(home, { recursive: true, force: true }));

// A stand-in for wrangler: migrations succeed, and `dev` exits at once, so start returns 1.
const fake = path.join(home, "fake-wrangler.mjs");
writeFileSync(fake, "process.exit(process.argv.includes('dev') ? 3 : 0);\n");
const base = {
  compatibility_date: "2026-11-01",
  compatibility_flags: ["nodejs_compat", "enable_request_signal"],
};
const runtime = {
  label: "test",
  layout: { main: "/x/worker.js", assetsDir: "/x/web", migrationsDir: "/x/migrations" },
  base,
  wrangler: { command: process.execPath, args: [fake], cwd: home },
  startCommand: () => "plinth start",
  log: () => {},
};

describe("plinth start after an upgrade", () => {
  it("adds the release's compatibility flags to a config an older release wrote", async () => {
    await setupInstance({ email: "me@example.com", home, port: "9771" }, runtime);
    const file = path.join(home, "plinth", "wrangler.jsonc");
    // What 0.3.x wrote: no enable_request_signal, an older date, and a key the operator added.
    const old = parseJsonc(readFileSync(file, "utf8"));
    old.compatibility_flags = ["nodejs_compat"];
    old.compatibility_date = "2026-06-01";
    old.limits = { cpu_ms: 60000 };
    writeFileSync(
      file,
      `// Generated by Plinth setup for "plinth".\n${JSON.stringify(old, null, 2)}\n`,
    );

    const log = console.log;
    console.log = () => {};
    let code;
    try {
      code = await startInstance({ home }, runtime);
    } finally {
      console.log = log;
    }
    assert.equal(code, 1);
    const text = readFileSync(file, "utf8");
    assert.match(text, /^\/\/ Generated by Plinth setup for "plinth"\.\n/);
    const now = parseJsonc(text);
    assert.deepEqual(now.compatibility_flags, ["nodejs_compat", "enable_request_signal"]);
    assert.equal(now.compatibility_date, "2026-11-01");
    assert.deepEqual(now.limits, { cpu_ms: 60000 });
    assert.equal(now.vars.APP_HOST, old.vars.APP_HOST);
  });
});
