// Copying files from another artifact into the version being published (copy_files on
// publish_artifact, update_artifact, start_upload and their REST mirrors; docs/spec.md "Copying
// files from another artifact", docs/security.md "Copies between artifacts").
//
// The rule, and why it is safe:
// - The source is named only by the caller's request (an id, slug or this instance's app link),
//   never by anything read from content, so no page, comment or design system can make the server
//   copy from somewhere.
// - Every source goes through policy.ts as the caller: decide("view") through requireArtifact, so a
//   caller who cannot view it gets the same 404 as for a missing id, and a token limited to one
//   artifact is refused before any lookup (mayCopyFiles). The target still needs `edit` (or a new
//   artifact), checked by the caller of this module before it runs.
// - It is checked once, at publish time. The copy is the target's own file from then on: the
//   bytes are written under the target's prefix and counted toward its size, its file count and
//   its owner's storage, and nothing ever loads across artifacts when the page is served. Losing
//   access to the source later changes nothing already published, like a file the caller had
//   downloaded and sent.
// - Paths are plain asset paths, the target type's asset rules apply, and a copy keeps its
//   source's content type: a file cannot change type by being copied under another ending.
import {
  ARTIFACT_ID_RE,
  type ArtifactTypeDef,
  type CopiedFrom,
  type CopyFileInput,
  type CopyRecord,
  LIMITS,
  SLUG_RE,
} from "@plinth/shared";
import type { ArtifactRow, VersionRow } from "../db/schema.ts";
import { ApiError } from "../lib/errors.ts";
import { nowIso } from "../lib/time.ts";
import { mayCopyFiles } from "../policy.ts";
import { decideFor, findArtifact, requireArtifact, requireVersion } from "./artifacts.ts";
import { checkAsset, requireTypeDef, typeHooks } from "./artifactTypes.ts";
import type { Ctx } from "./context.ts";
import type { Stager } from "./stage.ts";
import {
  assetContentType,
  type CopiedFromEntry,
  fileKey,
  type ManifestEntry,
  parseManifest,
  readText,
} from "./storage.ts";

/** One file to copy, authorized and located; its bytes are read only while staging. */
export interface CopyItem {
  to: string;
  from: string;
  artifactId: string;
  version: number;
  contentType: string;
  size: number;
  read(): Promise<Uint8Array>;
}

/** Every copy of one call, in the order given, and the time they are recorded with. */
export interface CopyPlan {
  items: CopyItem[];
  copiedAt: string;
}

const MB = (n: number) => `${Math.round((n / 1024 / 1024) * 10) / 10} MB`;

const baseType = (t: string) => (t.split(";")[0] ?? "").trim().toLowerCase();

function copyError(message: string, details: Record<string, unknown>): ApiError {
  return new ApiError("invalid_input", message, { field: "copy_files", ...details });
}

/**
 * The artifact a copy names, as findArtifact takes it: an id, a slug, or this instance's app link
 * (`<APP_ORIGIN>/a/<id or slug>`, a query or fragment ignored). Anything else is refused.
 */
export function copySourceRef(appOrigin: string, address: string): string {
  const s = address.trim();
  if (ARTIFACT_ID_RE.test(s)) return s;
  if (SLUG_RE.test(s.toLowerCase())) return s.toLowerCase();
  let url: URL | null = null;
  try {
    url = new URL(s);
  } catch {
    url = null;
  }
  const m =
    url && url.origin === appOrigin ? /^\/a\/([A-Za-z0-9-]{1,80})\/?$/.exec(url.pathname) : null;
  const ref = m?.[1]?.toLowerCase();
  if (ref && (ARTIFACT_ID_RE.test(ref) || SLUG_RE.test(ref))) return ref;
  throw copyError(`${s.slice(0, 120)} is not an artifact on this instance`, {
    reason: "copy_bad_address",
    artifact: s.slice(0, 300),
    next: `Name the artifact by its id, its slug or its link (${appOrigin}/a/<slug>)`,
  });
}

interface Source {
  row: ArtifactRow;
  version: VersionRow;
  def: ArtifactTypeDef;
  manifest: Map<string, ManifestEntry>;
  text?: Promise<string | null>;
}

/**
 * Authorize and locate every copy, before the publish rate and any R2 write: refused for a token
 * limited to one artifact, each source read as the caller with `view`, each file found in the
 * source version (or generated by its type), the target type's asset rules applied, and the counts
 * and bytes capped. Null when there is nothing to copy.
 */
export async function resolveCopies(
  ctx: Ctx,
  input: readonly CopyFileInput[] | undefined,
  target: ArtifactTypeDef,
): Promise<CopyPlan | null> {
  if (!input || input.length === 0) return null;
  if (!mayCopyFiles(ctx.principal)) {
    throw new ApiError(
      "forbidden",
      "A token limited to one artifact cannot copy files from other artifacts",
      {
        reason: "token_bound",
        field: "copy_files",
        next: "Send the files with assets instead",
      },
    );
  }
  if (input.length > LIMITS.maxCopyFiles) {
    throw copyError(`At most ${LIMITS.maxCopyFiles} files are copied in one call`, {
      reason: "copy_too_many",
      limit: LIMITS.maxCopyFiles,
    });
  }
  const sources = new Map<string, Source>();
  // One lookup per address and version asked for (an id and a slug of the same artifact meet below).
  const byAddress = new Map<string, Source>();
  const items: CopyItem[] = [];
  const seen = new Set<string>();
  let total = 0;
  for (const c of input) {
    const to = c.to ?? c.path;
    if (seen.has(to)) {
      throw copyError(`${to} is copied twice`, { reason: "copy_twice", path: to });
    }
    seen.add(to);
    const ref = copySourceRef(ctx.config.appOrigin, c.artifact);
    const asked = `${ref}@${c.version ?? "current"}`;
    let src = byAddress.get(asked);
    if (!src) {
      // As the caller, through policy.ts: a source they cannot view is a 404 like a missing one.
      const { artifact } = await requireArtifact(ctx, ref, "view");
      const version = await requireVersion(ctx, artifact, c.version ?? artifact.currentVersion);
      const key = `${artifact.id}@${version.number}`;
      src = sources.get(key);
      if (!src) {
        if (sources.size >= LIMITS.maxCopySources) {
          throw copyError(
            `Files are copied from at most ${LIMITS.maxCopySources} artifact versions in one call`,
            { reason: "copy_too_many_sources", limit: LIMITS.maxCopySources },
          );
        }
        src = {
          row: artifact,
          version,
          def: requireTypeDef(artifact.type),
          manifest: new Map(parseManifest(version.manifest).map((e) => [e.path, e])),
        };
        sources.set(key, src);
      }
      byAddress.set(asked, src);
    }
    items.push(await locate(ctx, src, c.path, to, target));
    total += items[items.length - 1]?.size ?? 0;
    if (total > LIMITS.maxCopyBytes) {
      throw new ApiError(
        "payload_too_large",
        `The files to copy are over ${MB(LIMITS.maxCopyBytes)} in one call`,
        { field: "copy_files", limit_bytes: LIMITS.maxCopyBytes, size_bytes: total },
      );
    }
  }
  return { items, copiedAt: nowIso() };
}

/** One copy: the source's stored file, or one its type generates; checked against the target. */
async function locate(
  ctx: Ctx,
  src: Source,
  from: string,
  to: string,
  target: ArtifactTypeDef,
): Promise<CopyItem> {
  const base = { to, from, artifactId: src.row.id, version: src.version.number };
  const stored = src.manifest.get(from);
  let item: CopyItem;
  if (stored) {
    const key = fileKey(src.row.id, src.version, stored);
    item = {
      ...base,
      contentType: stored.content_type,
      size: stored.size_bytes,
      async read() {
        const obj = await ctx.env.FILES.get(key);
        if (!obj) throw new ApiError("internal", `Missing stored file ${from}`);
        return new Uint8Array(await obj.arrayBuffer());
      },
    };
  } else {
    const hook = typeHooks(src.def).copySource;
    src.text ??= hook
      ? readText(ctx.env.FILES, `${src.version.r2Prefix}${src.def.sourcePath}`)
      : Promise.resolve(null);
    const text = await src.text;
    const made =
      hook && text !== null
        ? hook(text, from, { id: src.row.id, version: src.version.number })
        : null;
    if (!made) {
      throw copyError(`${from} is not a file of v${src.version.number} of that artifact`, {
        reason: "copy_missing_file",
        artifact: src.row.id,
        version: src.version.number,
        path: from,
        next: "get_artifact lists its files (a design system's are in get_design_system's files)",
      });
    }
    item = {
      ...base,
      contentType: made.contentType,
      size: made.bytes.byteLength,
      read: async () => made.bytes,
    };
  }
  // The copy keeps its content type: `to` must end the way `from` does (or name the same type).
  const served = assetContentType(to, item.contentType);
  if (baseType(served) !== baseType(item.contentType)) {
    throw copyError(
      `${to} would be served as ${baseType(served)}, but ${from} is ${baseType(item.contentType)}`,
      {
        reason: "copy_type_mismatch",
        path: to,
        next: `Give ${to} the same file ending as ${from}`,
      },
    );
  }
  checkAsset(target, to, served);
  return { ...item, contentType: served };
}

/** Stage every copy at its final path, one at a time within the stager's in-flight budget. */
export async function stageCopies(
  stager: Pick<Stager, "reserve" | "addCopy">,
  plan: CopyPlan | null,
): Promise<void> {
  for (const c of plan?.items ?? []) {
    await stager.reserve(c.size);
    const bytes = await c.read();
    const from: CopiedFromEntry = {
      artifact: c.artifactId,
      version: c.version,
      path: c.from,
      copied_at: plan?.copiedAt ?? nowIso(),
    };
    await stager.addCopy(c.to, bytes, c.contentType, from);
  }
}

/** The paths a plan writes (an update that carries the current files leaves these out). */
export function copyTargets(plan: CopyPlan | null): Set<string> {
  return new Set(plan?.items.map((c) => c.to) ?? []);
}

/** Group copied files by source version and copy time, in the order they appear. */
function groupCopies(entries: { path: string; from: CopiedFromEntry }[]): CopyRecord[] {
  const out = new Map<string, CopyRecord>();
  for (const { path, from } of entries) {
    const key = `${from.artifact}@${from.version}@${from.copied_at}`;
    let r = out.get(key);
    if (!r) {
      r = { artifact: from.artifact, version: from.version, copied_at: from.copied_at, files: [] };
      out.set(key, r);
    }
    r.files.push({ path, from: from.path });
  }
  return [...out.values()];
}

/** What a publish result says it copied. */
export function copyRecords(plan: CopyPlan | null): CopyRecord[] | undefined {
  if (!plan || plan.items.length === 0) return undefined;
  return groupCopies(
    plan.items.map((c) => ({
      path: c.to,
      from: { artifact: c.artifactId, version: c.version, path: c.from, copied_at: plan.copiedAt },
    })),
  );
}

/**
 * get_artifact's copied_from: the version's copied files by source, with the source's title and
 * current version only when the caller may view it now (policy.ts, as the caller).
 */
export async function copiedFromOf(
  ctx: Ctx,
  manifest: readonly ManifestEntry[],
): Promise<CopiedFrom[] | undefined> {
  const copied = manifest.flatMap((e) =>
    e.copied_from && typeof e.copied_from.artifact === "string"
      ? [{ path: e.path, from: e.copied_from }]
      : [],
  );
  if (copied.length === 0) return undefined;
  const seen = new Map<string, { title: string; current: number } | null>();
  const out: CopiedFrom[] = [];
  for (const r of groupCopies(copied)) {
    if (!seen.has(r.artifact)) {
      const row = ARTIFACT_ID_RE.test(r.artifact) ? await findArtifact(ctx, r.artifact) : null;
      const ok = row ? (await decideFor(ctx, row, "view")).allow : false;
      seen.set(r.artifact, row && ok ? { title: row.title, current: row.currentVersion } : null);
    }
    const shown = seen.get(r.artifact) ?? null;
    out.push({ ...r, title: shown?.title ?? null, current_version: shown?.current ?? null });
  }
  return out;
}
