export type IconName = keyof typeof ICONS;

const SVG_NS = "http://www.w3.org/2000/svg";

/** A 16px icon, hidden from assistive technology (its button carries the name). */
export function icon(doc: Document, name: IconName): SVGSVGElement {
  const svg = doc.createElementNS(SVG_NS, "svg");
  svg.setAttribute("viewBox", "0 0 256 256");
  svg.setAttribute("width", "16");
  svg.setAttribute("height", "16");
  svg.setAttribute("fill", "currentColor");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  const path = doc.createElementNS(SVG_NS, "path");
  path.setAttribute("d", ICONS[name]);
  svg.append(path);
  return svg;
}

/**
 * An icon button: `label` is its accessible name and its tooltip (data-tip, drawn by slides.css on
 * hover and keyboard focus).
 */
export function iconButton(
  doc: Document,
  name: IconName,
  label: string,
  onClick: () => void,
): HTMLButtonElement {
  const b = doc.createElement("button");
  b.type = "button";
  b.className = "plinth-slides__btn plinth-slides__btn--icon";
  b.setAttribute("aria-label", label);
  b.dataset.tip = label;
  b.append(icon(doc, name));
  b.addEventListener("click", onClick);
  return b;
}

/** Swaps a button's icon and its name (Pause timer and Resume timer). */
export function setIcon(b: HTMLButtonElement, name: IconName, label: string): void {
  const doc = b.ownerDocument;
  b.replaceChildren(icon(doc, name));
  b.setAttribute("aria-label", label);
  b.dataset.tip = label;
}
