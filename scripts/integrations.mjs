#!/usr/bin/env node
// Generate every per-harness integration from one source (docs/agents.md, and the design in
// docs/superpowers/specs/2026-11-14-agent-experience-design.md):
//
//   packages/shared/src/harnesses.ts           the registry: harnesses, plugin metadata, commands
//   integrations/skill/plinth-artifacts/SKILL.md the skill: the Plinth way, written once
//
// Outputs: the Claude Code and portable (Codex, ChatGPT) plugin in integrations/plugin/, both
// marketplace files, the Gemini CLI extension, the Cursor rule, the VS Code instructions file, the
// harness table in docs/agents.md, and the CLI's vendored modules in packages/cli/bin/client/vendor/
// (the shared OAuth client, and packages/shared/src/constants.ts with its types stripped). Never
// edit the outputs by hand.
//
//   pnpm integrations           write the outputs, and record the plugin sources' hash; refuses
//                               (exit 1, nothing written) when the skill or watcher changed and
//                               PLUGIN.version was not bumped since the last hash
//   pnpm integrations --same-version
//                               record it under the same version (a second skill edit on a branch
//                               that already bumped PLUGIN.version above main)
//   pnpm integrations --check   exit 1 if any output is missing or stale, or PLUGIN.skillHash or
//                               PLUGIN.skillHashVersion does not match (CI)
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { hashProblem, pluginSourcesHash, withRecordedHash } from "./plugin-sources.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const reg = await import(path.join(root, "packages/shared/src/harnesses.ts"));
const { PLUGIN, HOSTED_ORIGIN, SERVER_NAME, SKILL_NAME, SKILL_SOURCE, HARNESSES } = reg;

const skill = readFileSync(path.join(root, SKILL_SOURCE), "utf8");
const fm = /^---\n([\s\S]*?)\n---\n/.exec(skill);
if (!fm) throw new Error(`${SKILL_SOURCE} has no frontmatter`);
const skillBody = skill.slice(fm[0].length).trimStart();
const skillDescription = /^description:\s*(.+)$/m.exec(fm[1])?.[1]?.trim() ?? "";
const GENERATED = "Generated by scripts/integrations.mjs from packages/shared/src/harnesses.ts";
const json = (v) => `${JSON.stringify(v, null, 2)}\n`;
const hostedMcp = `${HOSTED_ORIGIN}/mcp`;
const meta = {
  name: PLUGIN.name,
  version: PLUGIN.version,
  description: PLUGIN.description,
  author: PLUGIN.author,
  homepage: PLUGIN.homepage,
  repository: PLUGIN.repository,
  license: PLUGIN.license,
  keywords: [...PLUGIN.keywords],
};

/** path (from the repo root) -> content */
const outputs = new Map();

// ---------- Claude Code plugin + portable plugin (Codex, ChatGPT) ----------
outputs.set(`integrations/plugin/skills/${SKILL_NAME}/SKILL.md`, skill);
outputs.set(
  "integrations/plugin/.claude-plugin/plugin.json",
  json({
    ...meta,
    privacyPolicyUrl: PLUGIN.privacyPolicyUrl,
    termsOfServiceUrl: PLUGIN.termsOfServiceUrl,
    supportUrl: PLUGIN.supportUrl,
    documentationUrl: PLUGIN.documentationUrl,
  }),
);
outputs.set(
  "integrations/plugin/.mcp.json",
  json({
    mcpServers: {
      [SERVER_NAME]: { type: "http", url: `\${PLINTH_URL:-${HOSTED_ORIGIN}}/mcp` },
    },
  }),
);
outputs.set(
  "integrations/plugin/plugin.json",
  json({
    $schema: "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
    ...meta,
    // Codex would otherwise pick up hooks/hooks.json, which is for Claude Code only (the mention
    // watcher answers @claude). An explicit hooks value replaces Codex's default discovery.
    extensions: { "com.openai": { hooks: [] } },
  }),
);

// Mention watcher (Claude Code only): a monitor that announces new @mentions, a SessionStart hook
// that lists waiting ones, and a skill to connect it. Source: integrations/watcher/.
const WATCHER = "scripts/plinth-mentions.mjs";
const watcherCmd = (sub) => `node "\${CLAUDE_PLUGIN_ROOT}/${WATCHER}" ${sub}`;
const watcherSource = (f) => readFileSync(path.join(root, "integrations/watcher", f), "utf8");
outputs.set(`integrations/plugin/${WATCHER}`, watcherSource("plinth-mentions.mjs"));
// The watcher imports the shared OAuth client from next to itself.
outputs.set("integrations/plugin/scripts/plinth-oauth.mjs", watcherSource("plinth-oauth.mjs"));
outputs.set(
  "integrations/plugin/skills/watch-mentions/SKILL.md",
  readFileSync(path.join(root, "integrations/watcher/watch-mentions/SKILL.md"), "utf8"),
);
outputs.set(
  "integrations/plugin/monitors/monitors.json",
  json([
    {
      name: "plinth-mentions",
      // Silent when Node is missing or the watcher is not connected (see /plinth:watch-mentions).
      command: `command -v node >/dev/null 2>&1 && exec ${watcherCmd("watch")}; exit 0`,
      description: "New @mention requests on your Plinth artifacts",
    },
  ]),
);
// The session note (Claude Code only, like the watcher): integrations/hooks/session-note.md.
const SESSION_NOTE = "hooks/session-note.md";
outputs.set(
  `integrations/plugin/${SESSION_NOTE}`,
  readFileSync(path.join(root, "integrations/hooks/session-note.md"), "utf8"),
);
outputs.set(
  "integrations/plugin/hooks/hooks.json",
  json({
    description:
      "Say where pages go (Plinth) and list Plinth @mention requests waiting when a session starts",
    hooks: {
      SessionStart: [
        {
          matcher: "startup|resume|clear",
          hooks: [
            {
              // Where pages go: the person installed Plinth for them. PLINTH_SESSION_NOTE=0 skips it.
              type: "command",
              command: `[ "\${PLINTH_SESSION_NOTE:-1}" = 0 ] || cat "\${CLAUDE_PLUGIN_ROOT}/${SESSION_NOTE}"; exit 0`,
              timeout: 5,
            },
            {
              type: "command",
              command: `command -v node >/dev/null 2>&1 && ${watcherCmd("pending")} 2>/dev/null; exit 0`,
              timeout: 15,
            },
          ],
        },
      ],
    },
  }),
);
outputs.set(
  "integrations/plugin/mcp.json",
  json({
    $schema: "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
    mcpServers: {
      [SERVER_NAME]: {
        // Only the fields the Agent Plugins schema allows (type, url, headers). Any other field,
        // `extensions` included, makes the entry invalid, and Codex and Copilot CLI then skip the
        // server. OAuth needs no hint: clients find it from the server's 401.
        type: "streamable-http",
        url: hostedMcp,
      },
    },
  }),
);
outputs.set(
  ".claude-plugin/marketplace.json",
  json({
    name: PLUGIN.name,
    description:
      "Plinth: a home for the HTML artifacts AI agents make, with owner-controlled sharing",
    owner: PLUGIN.author,
    plugins: [
      {
        name: PLUGIN.name,
        source: "./integrations/plugin",
        description: PLUGIN.description,
        version: PLUGIN.version,
        category: "productivity",
      },
    ],
  }),
);
outputs.set(
  ".agents/plugins/marketplace.json",
  json({
    name: PLUGIN.name,
    plugins: [
      {
        name: PLUGIN.name,
        source: { source: "local", path: "./integrations/plugin" },
        policy: { installation: "AVAILABLE", authentication: "ON_INSTALL" },
        category: "Productivity",
      },
    ],
  }),
);

// ---------- Claude Code plugin directory build ----------
// Anthropic's plugin directory accepts hooks, monitors and scripts only from verified
// organizations, and needs a fixed public URL for each MCP server. So the directory gets the skill
// and the hosted server only. The full plugin (watcher, session note, PLINTH_URL) stays the one in
// integrations/plugin, installed from this repository's marketplace.
const DIRECTORY = "integrations/plugin-directory";
const directorySkillEdits = [
  [
    "- In Claude Code with the Plinth plugin, `/plinth:watch-mentions` connects a watcher that tells the\n  session when new requests arrive, so the user does not have to ask you to check.",
    "- In Claude Code, the full Plinth plugin (`claude plugin marketplace add mr0b0t0/plinth`) adds\n  `/plinth:watch-mentions`, a watcher that tells the session when new requests arrive. Without it,\n  check `list_mentions` when the user asks.",
  ],
  [
    "URL (Claude Code: set `PLINTH_URL` to the instance's origin every time Claude Code starts, for\nexample `http://127.0.0.1:8788` for `npx @mr0b0t0/plinth`; without it the plugin's server is the\nhosted one).",
    "URL (Claude Code: add it with `claude mcp add --transport http plinth <origin>/mcp`; this plugin's\nserver is always the hosted one).",
  ],
];
let directorySkill = skill;
for (const [from, to] of directorySkillEdits) {
  if (!directorySkill.includes(from)) {
    throw new Error(
      `${DIRECTORY}: the skill no longer contains a passage this build rewrites:\n${from}`,
    );
  }
  directorySkill = directorySkill.replace(from, to);
}
outputs.set(`${DIRECTORY}/skills/${SKILL_NAME}/SKILL.md`, directorySkill);
outputs.set(
  `${DIRECTORY}/.claude-plugin/plugin.json`,
  json({
    ...meta,
    privacyPolicyUrl: PLUGIN.privacyPolicyUrl,
    termsOfServiceUrl: PLUGIN.termsOfServiceUrl,
    supportUrl: PLUGIN.supportUrl,
    documentationUrl: PLUGIN.documentationUrl,
  }),
);
outputs.set(
  `${DIRECTORY}/.mcp.json`,
  json({ mcpServers: { [SERVER_NAME]: { type: "http", url: hostedMcp } } }),
);

// ---------- Gemini CLI extension ----------
outputs.set(
  "integrations/gemini/gemini-extension.json",
  json({
    name: PLUGIN.name,
    version: PLUGIN.version,
    description: PLUGIN.description,
    mcpServers: { [SERVER_NAME]: { httpUrl: hostedMcp } },
    contextFileName: "GEMINI.md",
  }),
);
outputs.set(
  "integrations/gemini/GEMINI.md",
  `<!-- ${GENERATED} -->\n# Plinth\n\nThe \`${SERVER_NAME}\` MCP server publishes HTML pages ("artifacts") for the user on Plinth.\nWhen you make a page, publish, update or share one, or address comments on one, follow the\n\`${SKILL_NAME}\` skill bundled with this extension.\n`,
);
outputs.set(`integrations/gemini/skills/${SKILL_NAME}/SKILL.md`, skill);

// ---------- Cursor rule (agent-requested) ----------
outputs.set(
  `integrations/cursor/${SKILL_NAME}.mdc`,
  `---\ndescription: ${skillDescription}\nalwaysApply: false\n---\n<!-- ${GENERATED} -->\n\n${skillBody}`,
);

// ---------- VS Code instructions file ----------
outputs.set(
  `integrations/vscode/${SKILL_NAME}.instructions.md`,
  `---\nname: ${SKILL_NAME}\ndescription: ${skillDescription}\n---\n<!-- ${GENERATED} -->\n\n${skillBody}`,
);

// ---------- the harness table in docs/agents.md ----------
const KIND = {
  plugin: "Plugin",
  extension: "Extension",
  "rule-file": "Rule file",
  "skill-upload": "Uploaded skill",
  "server-only": "Server instructions",
};
const table = [
  "| Harness | Its own artifacts | Reaches a local instance | Plinth guidance | Checked against the real harness |",
  "| --- | --- | --- | --- | --- |",
  ...HARNESSES.map(
    (h) =>
      `| ${h.label} | ${h.nativeArtifacts ?? "none"} | ${h.reachesLocal ? "yes" : "no"} | ${KIND[h.guidance.kind]}: ${h.guidance.summary.replaceAll("|", "\\|")} | ${h.verified ? "yes" : "not yet"} |`,
  ),
].join("\n");
const agentsDoc = path.join(root, "docs/agents.md");
const startMark = "<!-- harnesses:start -->";
const endMark = "<!-- harnesses:end -->";
const doc = readFileSync(agentsDoc, "utf8");
const a = doc.indexOf(startMark);
const b = doc.indexOf(endMark);
if (a < 0 || b < a) throw new Error(`docs/agents.md needs ${startMark} and ${endMark}`);
outputs.set(
  "docs/agents.md",
  `${doc.slice(0, a + startMark.length)}\n<!-- ${GENERATED} -->\n\n${table}\n\n${doc.slice(b)}`,
);

// ---------- the CLI's vendored modules ----------
// The client commands (packages/cli/bin/client/) run from the npm package and from a clean checkout
// without a build, so they import committed copies, never the gitignored runtime/ folder.
const VENDOR = "packages/cli/bin/client/vendor";
outputs.set(`${VENDOR}/plinth-oauth.mjs`, watcherSource("plinth-oauth.mjs"));
{
  const src = "packages/shared/src/constants.ts";
  const stripped = stripTypeScriptTypes(readFileSync(path.join(root, src), "utf8"));
  const header = `// Generated by scripts/integrations.mjs from ${src}, types stripped.\n`;
  outputs.set(`${VENDOR}/constants.mjs`, biomeFormat(`${VENDOR}/constants.mjs`, header + stripped));
}

/** Format generated JavaScript the way `pnpm lint` expects (type stripping leaves blanks). */
function biomeFormat(rel, code) {
  const bin = path.join(root, "node_modules/.bin/biome");
  const r = spawnSync(bin, ["format", `--stdin-file-path=${rel}`], {
    cwd: root,
    input: code,
    encoding: "utf8",
  });
  if (r.status !== 0) throw new Error(`biome format failed for ${rel}:\n${r.stderr}`);
  return r.stdout;
}

// ---------- the plugin version guard ----------
// Installed plugins update only when PLUGIN.version changes, so a change to what the plugin ships
// must come with a bump. A new hash is recorded only under a new version (scripts/plugin-sources.mjs).
const HARNESSES_TS = "packages/shared/src/harnesses.ts";
const sourcesHash = pluginSourcesHash(root);
const hashIssue = hashProblem({
  recorded: PLUGIN.skillHash,
  recordedVersion: PLUGIN.skillHashVersion,
  actual: sourcesHash,
  version: PLUGIN.version,
  sameVersion: process.argv.includes("--same-version"),
});
if (hashIssue && !check) {
  if (hashIssue.refuse) {
    console.error(hashIssue.message);
    process.exit(1);
  }
  const file = path.join(root, HARNESSES_TS);
  writeFileSync(file, withRecordedHash(readFileSync(file, "utf8"), sourcesHash, PLUGIN.version));
  console.log(
    `Recorded the plugin sources' hash under PLUGIN.version ${PLUGIN.version} in ${HARNESSES_TS}.`,
  );
}

// ---------- write or check ----------
const stale = [];
for (const [rel, content] of outputs) {
  const file = path.join(root, rel);
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (current === content) continue;
  if (check) stale.push(rel);
  else {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
if (check) {
  if (hashIssue) console.error(hashIssue.message);
  if (stale.length) {
    console.error(`Stale integration files (run pnpm integrations):\n  ${stale.join("\n  ")}`);
  }
  if (hashIssue || stale.length) process.exit(1);
  console.log(`Integrations are up to date (${outputs.size} files).`);
}
