// ---------- the harness table in docs/agents.md ----------
const KIND = {
  plugin: "Plugin",
  extension: "Extension",
  "rule-file": "Rule file",
  "skill-upload": "Uploaded skill",
  "server-only": "Server instructions",
};
const table = [
  "| Harness | Its own artifacts | Reaches a local instance | Plinth guidance | Checked against the real harness |",
  "| --- | --- | --- | --- | --- |",
  ...HARNESSES.map(
    (h) =>
      `| ${h.label} | ${h.nativeArtifacts ?? "none"} | ${h.reachesLocal ? "yes" : "no"} | ${KIND[h.guidance.kind]}: ${h.guidance.summary.replaceAll("|", "\\|")} | ${h.verified ? "yes" : "not yet"} |`,
  ),
].join("\n");
const agentsDoc = path.join(root, "docs/agents.md");
const startMark = "<!-- harnesses:start -->";
const endMark = "<!-- harnesses:end -->";
const doc = readFileSync(agentsDoc, "utf8");
const a = doc.indexOf(startMark);
const b = doc.indexOf(endMark);
if (a < 0 || b < a) throw new Error(`docs/agents.md needs ${startMark} and ${endMark}`);
outputs.set(
  "docs/agents.md",
  `${doc.slice(0, a + startMark.length)}\n<!-- ${GENERATED} -->\n\n${table}\n\n${doc.slice(b)}`,
);

// ---------- the CLI's vendored modules ----------
// The client commands (packages/cli/bin/client/) run from the npm package and from a clean checkout
// without a build, so they import committed copies, never the gitignored runtime/ folder.
const VENDOR = "packages/cli/bin/client/vendor";
outputs.set(`${VENDOR}/plinth-oauth.mjs`, watcherSource("plinth-oauth.mjs"));
{
  const src = "packages/shared/src/constants.ts";
  const stripped = stripTypeScriptTypes(readFileSync(path.join(root, src), "utf8"));
  const header = `// Generated by scripts/integrations.mjs from ${src}, types stripped.\n`;
  outputs.set(`${VENDOR}/constants.mjs`, biomeFormat(`${VENDOR}/constants.mjs`, header + stripped));
}

/** Format generated JavaScript the way `pnpm lint` expects (type stripping leaves blanks). */
function biomeFormat(rel, code) {
  const bin = path.join(root, "node_modules/.bin/biome");
  const r = spawnSync(bin, ["format", `--stdin-file-path=${rel}`], {
    cwd: root,
    input: code,
    encoding: "utf8",
  });
  if (r.status !== 0) throw new Error(`biome format failed for ${rel}:\n${r.stderr}`);
  return r.stdout;
}

// ---------- the plugin version guard ----------
// Installed plugins update only when PLUGIN.version changes, so a change to what the plugin ships
// must come with a bump. A new hash is recorded only under a new version (scripts/plugin-sources.mjs).
const HARNESSES_TS = "packages/shared/src/harnesses.ts";
const sourcesHash = pluginSourcesHash(root);
const hashIssue = hashProblem({
  recorded: PLUGIN.skillHash,
  recordedVersion: PLUGIN.skillHashVersion,
  actual: sourcesHash,
  version: PLUGIN.version,
  sameVersion: process.argv.includes("--same-version"),
});
if (hashIssue && !check) {
  if (hashIssue.refuse) {
    console.error(hashIssue.message);
    process.exit(1);
  }
  const file = path.join(root, HARNESSES_TS);
  writeFileSync(file, withRecordedHash(readFileSync(file, "utf8"), sourcesHash, PLUGIN.version));
  console.log(
    `Recorded the plugin sources' hash under PLUGIN.version ${PLUGIN.version} in ${HARNESSES_TS}.`,
  );
}

// ---------- write or check ----------
const stale = [];
for (const [rel, content] of outputs) {
  const file = path.join(root, rel);
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (current === content) continue;
  if (check) stale.push(rel);
  else {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
if (check) {
  if (hashIssue) console.error(hashIssue.message);
  if (stale.length) {
    console.error(`Stale integration files (run pnpm integrations):\n  ${stale.join("\n  ")}`);
  }
  if (hashIssue || stale.length) process.exit(1);
  console.log(`Integrations are up to date (${outputs.size} files).`);
}
